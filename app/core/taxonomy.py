# -------------------------------------------------------------------------
# 4. Centralized Taxonomy Service & Mapping Engine
# -------------------------------------------------------------------------


class TaxonomyService:
    """Authoritative service for resolving, querying, and normalizing STEM domains and categories."""

    def __init__(self, domains: Optional[List[STEMDomain]] = None) -> None:
        self._domains = domains or STEM_DOMAINS
        self._domain_by_slug: Dict[str, STEMDomain] = {}
        self._slug_to_canonical: Dict[str, str] = {}

        for domain in self._domains:
            self._domain_by_slug[domain.slug] = domain
            self._slug_to_canonical[domain.slug] = domain.slug
            for alias in domain.aliases:
                self._slug_to_canonical[alias] = domain.slug

    def get_primary_domains(self) -> List[STEMDomain]:
        """Return the 12 core foundational STEM disciplines."""
        return [d for d in self._domains if d.is_primary_domain]

    def get_cross_cutting_domains(self) -> List[STEMDomain]:
        """Return regional and policy cross-cutting knowledge domains."""
        return [d for d in self._domains if d.is_cross_cutting]

    def get_all_domains(self) -> List[STEMDomain]:
        """Return all 16 registered rich domains."""
        return list(self._domains)

    def get_domain(self, slug: str) -> Optional[STEMDomain]:
        """Retrieve a domain by its primary slug or any of its aliases."""
        clean_slug = slug.strip().lower()
        canonical = self._slug_to_canonical.get(clean_slug, clean_slug)
        return self._domain_by_slug.get(canonical)

    def resolve_canonical_slug(self, slug: str) -> str:
        """Resolve an alias or historical slug to its primary domain canonical slug."""
        clean = slug.strip().lower()
        return self._slug_to_canonical.get(clean, clean)

    def get_keywords_for_slug(self, slug: str) -> List[str]:
        """Retrieve keyword list for any historical or standardized category slug."""
        clean = slug.strip().lower()
        if clean in CATEGORY_KEYWORDS:
            return CATEGORY_KEYWORDS[clean]
        domain = self.get_domain(clean)
        return domain.keywords if domain else []

    def get_interests_options(self) -> List[Tuple[str, str, str]]:
        """Return curated domain list formatted for onboarding and interest selector: (Name, Slug, Emoji)."""
        options: List[Tuple[str, str, str]] = []
        for d in self.get_primary_domains():
            options.append((d.name, d.slug, d.emoji))
        for d in self.get_cross_cutting_domains():
            options.append((d.name, d.slug, d.emoji))
        return options


# Global taxonomy singleton instance
taxonomy = TaxonomyService()
